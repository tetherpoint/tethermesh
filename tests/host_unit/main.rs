// ===========================================================================
// L4 — fuzzing the parse path.
//
// This complements the Kani harnesses rather than duplicating them. Kani
// proves the parse path panic-free over EVERY input, but only up to a bounded
// length -- eight bytes for the wire reader, sixteen for a header -- because
// an unbounded proof does not terminate. These run unbounded lengths over
// randomised bytes, which is weaker per input and reaches inputs a bounded
// proof never sees: length prefixes that overrun, nested wrappers, payloads at
// and beyond MAX_PAYLOAD.
//
// The panic-free CLAIM rests on tools/check_rust_rules.sh inspecting the built
// artifact, and PLAN.md is explicit that fuzzing alone only shows nothing
// crashed today. These are here to reach the cases that argument does not
// cover by itself, not to replace it.
// ===========================================================================

/// A tiny xorshift PRNG, seeded fixed so a failure is reproducible.
///
/// Deliberately not `rand`: a fuzz failure that cannot be replayed is a bug
/// report nobody can act on, and the seed is printed in every assertion below.
struct Xor(u64);

impl Xor {
    fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }
    fn fill(&mut self, buf: &mut [u8]) {
        for chunk in buf.chunks_mut(8) {
            let v = self.next_u64().to_le_bytes();
            for (d, s) in chunk.iter_mut().zip(v.iter()) {
                *d = *s;
            }
        }
    }
    fn below(&mut self, n: usize) -> usize {
        if n == 0 { 0 } else { (self.next_u64() % (n as u64)) as usize }
    }
}

/// Every entry point on the parse path, over random bytes of every length.
///
/// The assertion is implicit and total: a panic anywhere fails the test. What
/// is asserted explicitly is the property that a *successful* parse must be
/// self-consistent, because a decoder that accepts garbage and returns
/// something is worse than one that rejects it.
#[test]
fn the_parse_path_survives_random_bytes_at_every_length() {
    let mut rng = Xor(0x5EED_1234_ABCD_0001);
    let mut buf = [0u8; 512];

    for round in 0..20_000 {
        let len = rng.below(buf.len() + 1);
        let bytes = &mut buf[..len];
        rng.fill(bytes);

        // Header: decode must round-trip exactly when it succeeds.
        if let Some(h) = Header::decode(bytes) {
            assert_eq!(
                h.encode().as_slice(),
                &bytes[..HEADER_LEN],
                "header round-trip broke, round {round}, len {len}"
            );
            // Relaying spends exactly one hop or refuses.
            match h.relayed_by(0x1234_5678) {
                Some(r) => assert_eq!(r.hop_limit + 1, h.hop_limit),
                None => assert_eq!(h.hop_limit, 0),
            }
        }

        // Frame helpers must report rather than read past.
        let _ = frame::peek_header(bytes);
        let _ = frame::payload(bytes);

        // The schema-free wire reader must terminate on any input.
        let mut r = Reader::new(bytes);
        let mut steps = 0;
        while steps < 4096 {
            match r.next_field() {
                Ok(Some(_)) => steps += 1,
                _ => break,
            }
        }

        // Wrappers: a successful decode must re-encode and re-decode stably.
        if let Ok(d) = Data::decode(bytes) {
            let mut out = [0u8; 640];
            if let Ok(n) = d.encode(&mut out) {
                let again = Data::decode(&out[..n]).expect("re-decode of our own encoding");
                assert_eq!(again.portnum, d.portnum, "portnum unstable, round {round}");
                assert_eq!(again.payload, d.payload, "payload unstable, round {round}");
            }
        }
        if let Ok(u) = User::decode(bytes) {
            let mut out = [0u8; 640];
            if let Ok(n) = u.encode(&mut out) {
                let again = User::decode(&out[..n]).expect("re-decode of our own encoding");
                assert_eq!(again.id, u.id, "user id unstable, round {round}");
            }
        }
        if let Ok(c) = ChannelSettings::decode(bytes) {
            let mut out = [0u8; 640];
            let _ = c.encode(&mut out);
        }
    }
}

/// Mutated real frames — the neighbourhood of valid input, which uniform
/// random bytes almost never reaches.
///
/// A 16-byte header has 2^128 possible values, so random bytes essentially
/// never produce a *plausible* frame. Flipping bits in captured traffic
/// explores the region where a decoder is most likely to be wrong: valid
/// length prefixes pointing slightly too far, almost-correct wire types,
/// off-by-one payload bounds.
#[test]
fn mutated_captures_are_rejected_or_handled_but_never_panic() {
    let doc = fs::read_to_string(captures_dir().join("on_air_frames.json")).unwrap();
    let mut originals: Vec<Vec<u8>> = Vec::new();
    let mut rest = doc.as_str();
    while let Some(i) = rest.find("\"raw_hex\"") {
        rest = &rest[i..];
        if let Some(h) = json_str(rest, "raw_hex") {
            originals.push(hex_to_bytes(h));
        }
        rest = &rest[9..];
    }
    assert!(!originals.is_empty(), "no captured frames to mutate");

    let mut rng = Xor(0x0FF1_CE00_D15E_A5E5);
    let mut mutations = 0u32;

    for base in &originals {
        for _ in 0..4_000 {
            let mut f = base.clone();
            // One to three bit flips, or a length-changing truncation.
            let flips = 1 + rng.below(3);
            for _ in 0..flips {
                if f.is_empty() { break; }
                let i = rng.below(f.len());
                let bit = rng.below(8);
                f[i] ^= 1u8 << bit;
            }
            if rng.below(4) == 0 && !f.is_empty() {
                let keep = rng.below(f.len());
                f.truncate(keep);
            }
            mutations += 1;

            if let Some(h) = Header::decode(&f) {
                assert_eq!(h.encode().as_slice(), &f[..HEADER_LEN]);
            }
            let _ = frame::peek_header(&f);
            if let Ok(p) = frame::payload(&f) {
                assert!(p.len() <= frame::MAX_PAYLOAD, "payload exceeded MAX_PAYLOAD");
            }
            let mut r = Reader::new(&f);
            let mut steps = 0;
            while steps < 4096 {
                match r.next_field() {
                    Ok(Some(_)) => steps += 1,
                    _ => break,
                }
            }
            let _ = Data::decode(&f);
            let _ = User::decode(&f);
        }
    }
    assert!(mutations > 1_000, "fuzzer did too little work to mean anything");
}

/// Build a PKI direct message for the bench to transmit — L6's open half.
///
/// L6's gate has two directions. Decrypting a DM a stock node sent us is done
/// and is covered by `x25519_reproduces_the_bench_exchange_and_decrypts_the_message`.
/// This is the other one: **emit a DM a stock node accepts.**
///
/// The construction is `WIRE_REFERENCE.md`'s, measured rather than assumed:
///
/// ```text
/// key agreement  X25519
/// KDF            SHA-256 over the raw shared secret
/// cipher         AES-256-CCM, 8-byte tag, full 32-byte key
/// nonce (13 B)   packet_id (u32 LE) || extra_nonce (4 B) || from (u32 LE) || 0x00
/// payload        ciphertext || tag(8) || extra_nonce(4)
/// channel byte   0x00 marks a PKI packet on the wire
/// ```
///
/// **The frame is assembled here rather than through `frame::encode`**, and
/// that is not a shortcut. `frame::encode` applies the channel AES-CTR layer
/// unconditionally, which is right for channel traffic and wrong here: a PKI
/// payload is already sealed by CCM, and a second keystream over it would
/// produce a frame no one can read. The two paths genuinely differ.
///
/// Environment, all required, because none of them may be guessed:
/// `TM_PRIV` our private scalar, `PEER_PUB` the peer's public key, `PEER_NODE`
/// their node number. `DM_ID` overrides the packet id — a repeated `(from, id)`
/// is silently dropped by their duplicate suppression, which is
/// indistinguishable from a frame that never arrived and has already cost this
/// project two debugging cycles.
#[test]
fn emit_pki_dm_frame_for_the_bench() {
    const FROM: u32 = 0x7e57_0001;

    let (Ok(priv_hex), Ok(peer_hex), Ok(peer_node)) = (
        std::env::var("TM_PRIV"),
        std::env::var("PEER_PUB"),
        std::env::var("PEER_NODE"),
    ) else {
        // Not a failure: the suite must pass on a bare clone with no bench.
        println!("PKI_DM_FRAME skipped — set TM_PRIV, PEER_PUB, PEER_NODE");
        return;
    };

    let id: u32 = std::env::var("DM_ID").ok()
        .and_then(|v| u32::from_str_radix(v.trim_start_matches("0x"), 16).ok())
        .unwrap_or(0x0bad_d100);
    let extra_nonce: u32 = std::env::var("DM_EXTRA").ok()
        .and_then(|v| u32::from_str_radix(v.trim_start_matches("0x"), 16).ok())
        .unwrap_or(0x1122_3344);
    let text = std::env::var("DM_TEXT").unwrap_or_else(|_| "tethermesh-pki-1".into());
    let to = u32::from_str_radix(peer_node.trim_start_matches("0x"), 16)
        .expect("PEER_NODE must be hex");

    let mut sk = [0u8; 32];
    sk.copy_from_slice(&hex_to_bytes(&priv_hex));
    let mut pk = [0u8; 32];
    pk.copy_from_slice(&hex_to_bytes(&peer_hex));

    // Agreement, then the KDF. Both our own code, end to end.
    let shared = x25519(&sk, &pk).expect("peer key is small-order");
    let key = sha256(&shared);

    // The plaintext is an ordinary Data wrapper; PKI changes the envelope,
    // not the payload schema.
    let data = Data {
        portnum: PortNum::TEXT_MESSAGE_APP.0,
        payload: text.as_bytes(),
        want_response: false,
        ..Data::default()
    };
    let mut plain = [0u8; 200];
    let plen = data.encode(&mut plain).expect("Data encode");

    // CCM in place: buffer carries plaintext, then ciphertext||tag.
    let mut work = [0u8; 220];
    work[..plen].copy_from_slice(&plain[..plen]);
    let mut nonce13 = [0u8; 13];
    nonce13[..4].copy_from_slice(&id.to_le_bytes());
    nonce13[4..8].copy_from_slice(&extra_nonce.to_le_bytes());
    nonce13[8..12].copy_from_slice(&FROM.to_le_bytes());
    // nonce13[12] stays 0.
    let sealed = ccm_encrypt_in_place(&key, &nonce13, &mut work, plen, CCM_TAG_LEN)
        .expect("CCM seal");

    let header = Header {
        to,
        from: FROM,
        id,
        hop_limit: 3,
        hop_start: 3,
        // DM_ACK=1 requests an acknowledgement, which is how a real ROUTING
        // response is obtained rather than guessed at.
        want_ack: std::env::var("DM_ACK").is_ok(),
        channel: 0x00, // the PKI marker
        relay_node: (FROM & 0xFF) as u8,
        ..Header::default()
    };

    let mut frame_bytes = Vec::with_capacity(HEADER_LEN + sealed + 4);
    frame_bytes.extend_from_slice(&header.encode());
    frame_bytes.extend_from_slice(&work[..sealed]);
    frame_bytes.extend_from_slice(&extra_nonce.to_le_bytes());

    // Prove it round-trips under our own reader before putting it on the air.
    // A frame we cannot decrypt ourselves is not one to spend an over-the-air
    // debugging cycle on.
    {
        let body = &frame_bytes[HEADER_LEN..];
        let mut back = body[..body.len() - 4].to_vec();
        let n = ccm_decrypt_in_place(&key, &nonce13, &mut back, CCM_TAG_LEN)
            .expect("our own DM must decrypt under our own reader");
        let d = Data::decode(&back[..n]).expect("decode our own Data");
        assert_eq!(d.payload, text.as_bytes(), "round-trip changed the text");
        assert_eq!(d.portnum, PortNum::TEXT_MESSAGE_APP.0);
    }

    println!(
        "PKI_DM_FRAME {}",
        frame_bytes.iter().map(|b| format!("{b:02x}")).collect::<String>()
    );
    println!("PKI_DM_TO {to:08x} ID {id:08x} LEN {}", frame_bytes.len());
}

/// Every measured modem preset, checked against our own airtime model.
///
/// L0 item 6. `tests/captures/modem_presets.json` records what each preset
/// actually programs into the radio, read from a stock node's own boot report
/// after writing `LoRaConfig.modem_preset` over the serial admin API.
///
/// **This is the check that generalises `airtime.rs` beyond one data point.**
/// Until now the model was anchored by LongFast alone: sixteen preamble
/// symbols reproducing a reported 131 ms. Nine presets spanning SF7-SF12 and
/// 125/250/500 kHz is a far stronger constraint, and a symbol-time formula
/// that was accidentally right at one spreading factor will not survive it.
///
/// Coding rate is deliberately absent from the fixture and so is absent here.
/// The node does not report it, and the reported bitrate cannot invert to it:
/// the ratio of bitrate to `SF*BW/2^SF` drifts with SF (0.697 at SF11, 0.725
/// at SF7), so that figure carries packet overhead of a shape we have not
/// established. Guessing it would be assuming a formula to manufacture a fact.
#[test]
fn every_measured_modem_preset_agrees_with_our_airtime_model() {
    let doc = fs::read_to_string(captures_dir().join("modem_presets.json"))
        .expect("cannot read modem_presets.json");

    let mut checked = 0usize;
    let mut rest = doc.as_str();
    while let Some(i) = rest.find("\"preset\":") {
        rest = &rest[i + 9..];
        let block_end = rest.find('}').unwrap_or(rest.len());
        let block = &rest[..block_end];

        // Only rows the node accepted carry real parameters.
        if !block.contains("\"valid\": true") {
            continue;
        }
        let num = |key: &str| -> Option<f64> {
            let k = format!("\"{key}\":");
            let j = block.find(&k)? + k.len();
            let tail = block[j..].trim_start();
            let end = tail.find(|c: char| c != '.' && c != '-' && !c.is_ascii_digit())
                .unwrap_or(tail.len());
            tail[..end].parse().ok()
        };

        let (Some(bw_khz), Some(sf), Some(pre_ms)) =
            (num("bandwidth_khz"), num("spreading_factor"), num("preamble_ms"))
        else {
            continue;
        };

        let params = ModemParams {
            spreading_factor: sf as u8,
            bandwidth_hz: (bw_khz * 1000.0) as u32,
            ..ModemParams::LONGFAST
        };
        let sym = params.symbol_time_us().expect("symbol time for a measured preset");

        // The node reports preamble time in whole milliseconds, so allow the
        // rounding it must have done -- but nothing more.
        let modelled_pre_us = u32::from(params.preamble_symbols) * sym;
        let reported_pre_us = (pre_ms * 1000.0) as u32;
        let diff = modelled_pre_us.abs_diff(reported_pre_us);
        assert!(
            diff <= 1000,
            "SF{sf} BW{bw_khz}kHz: modelled preamble {modelled_pre_us} us vs reported \
             {reported_pre_us} us, off by {diff} us -- more than integer-ms rounding"
        );

        // Airtime must be computable and sane at the largest legal payload.
        let at = params.airtime_us(frame::MAX_PAYLOAD as u16).expect("airtime");
        assert!(at > modelled_pre_us, "airtime must exceed its own preamble");

        // Coding rate, measured 2026-08-16 by timing rather than assumed. Every
        // valid preset came back 4/5, so the preset table varies spreading
        // factor and bandwidth only. If a future capture ever shows otherwise
        // this must fail rather than quietly average out.
        assert!(
            block.contains("\"coding_rate\": \"4/5\""),
            "SF{sf} BW{bw_khz}kHz: fixture no longer records CR 4/5. Every preset \
             measured 4/5; a different value is a finding to adjudicate, not a \
             constant to update"
        );
        assert_eq!(
            ModemParams::LONGFAST.coding_rate, 1,
            "LONGFAST must stay at the measured 4/5 (coding_rate index 1)"
        );
        checked += 1;
    }

    assert_eq!(
        checked, 9,
        "expected nine valid presets in the fixture; a changed fixture must be \
         re-adjudicated rather than silently checked less"
    );
}

/// The measured contention window, tied to the constant that claims it.
///
/// `tests/captures/contention_window.json` records 33 relays observed off a
/// stock node. This asserts the two properties that measurement settled and
/// that `ContentionWindow::MESHTASTIC_SHAPE` now depends on, so the constant
/// cannot drift from its evidence.
///
/// **The SNR axis of that measurement failed** — 23 dB of transmit power moved
/// reported SNR by 1.25 dB, because at 3 m the link sits ~88 dB above
/// sensitivity and LoRa's reported SNR is pegged. So this checks the window at
/// ONE SNR. The low-SNR end, and therefore the slope, remain unmeasured, and
/// the fixture says so in `primary_axis_failed`.
#[test]
fn the_measured_contention_window_matches_the_constant_that_cites_it() {
    let doc = fs::read_to_string(captures_dir().join("contention_window.json"))
        .expect("cannot read contention_window.json");

    // Every observed delay was an exact multiple of the 28 ms slot time. That
    // is what makes a slot-counted window the right model at all.
    let mut delays: Vec<u32> = Vec::new();
    let mut rest = doc.as_str();
    while let Some(i) = rest.find("\"tx_delay_ms\":") {
        rest = &rest[i + 14..];
        let tail = rest.trim_start();
        let end = tail.find(|c: char| !c.is_ascii_digit()).unwrap_or(tail.len());
        if let Ok(v) = tail[..end].parse::<u32>() {
            delays.push(v);
        }
    }
    assert!(delays.len() >= 30, "expected the full sample, got {}", delays.len());

    for d in &delays {
        assert_eq!(d % 28, 0, "delay {d} ms is not a multiple of the 28 ms slot time");
    }

    // The backoff is a random draw, not a fixed delay. If this spread ever
    // collapsed, `Relay::After` handing back a window rather than a wait would
    // no longer be justified.
    let lo = *delays.iter().min().expect("min");
    let hi = *delays.iter().max().expect("max");
    assert!(
        hi - lo > 2_000,
        "delays spread only {} ms at near-constant SNR; that looks deterministic, \
         and would invalidate treating the result as a window",
        hi - lo
    );

    // The constant must cover what was actually observed.
    let max_slots_seen = u8::try_from(hi / 28).expect("slot count fits");
    assert!(
        ContentionWindow::MESHTASTIC_SHAPE.max_slots >= max_slots_seen,
        "MESHTASTIC_SHAPE.max_slots is {} but {max_slots_seen} slots were observed \
         on hardware — the constant must not claim a smaller window than measured",
        ContentionWindow::MESHTASTIC_SHAPE.max_slots
    );
}

