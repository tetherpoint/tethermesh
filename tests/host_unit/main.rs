/// An acknowledgement stops the retransmissions.
#[test]
fn acknowledging_retires_the_entry_and_stops_retransmission() {
    let mut ob: Outbox<2> = Outbox::new(RetryPolicy::MEASURED_CEILING);
    let mut duty = wide_duty();
    ob.track(&probe_frame(0xAA00_0003), 0).unwrap();

    assert!(ob.acknowledge(0xAA00_0003), "must match the tracked id");
    assert!(ob.is_empty());
    assert!(ob.next_due(7_000_000, 100_000, &mut duty).is_none());
    assert!(!ob.acknowledge(0xAA00_0003), "already retired");
    assert!(!ob.acknowledge(0xDEAD_BEEF), "an unmatched ack is ordinary, not an error");
}

/// Giving up is reported, not silent.
#[test]
fn exhausting_the_attempts_reports_the_give_up() {
    let mut ob: Outbox<2> = Outbox::new(RetryPolicy::MEASURED_CEILING);
    let mut duty = wide_duty();
    ob.track(&probe_frame(0xAA00_0004), 0).unwrap();
    let _ = ob.next_due(7_000_000, 100_000, &mut duty);
    let _ = ob.next_due(14_000_000, 100_000, &mut duty);

    assert!(ob.reap(14_000_000).is_none(), "last interval has not elapsed");
    assert_eq!(ob.reap(21_000_000), Some((0x7e57_0001, 0xAA00_0004)));
    assert!(ob.is_empty());
    assert!(ob.reap(99_000_000).is_none());
}

/// The duty budget gates retransmission, and deciding does not spend it.
#[test]
fn retransmission_respects_the_duty_budget_without_charging_it() {
    let mut ob: Outbox<2> = Outbox::new(RetryPolicy::MEASURED_CEILING);
    ob.track(&probe_frame(0xAA00_0005), 0).unwrap();

    // 1 ms of budget against a 100 ms frame.
    let mut tight = DutyCycle::new(1, 1000, 0).unwrap();
    assert!(ob.next_due(7_000_000, 100_000, &mut tight).is_none(), "budget must gate it");

    let mut wide = wide_duty();
    assert!(ob.next_due(7_000_000, 100_000, &mut wide).is_some());
    assert_eq!(wide.used_us(), 0, "deciding must not bill airtime the caller has not sent");
}

/// Fixed capacity is a design property, and it reports rather than overwrites.
#[test]
fn a_full_outbox_refuses_rather_than_dropping_something() {
    let mut ob: Outbox<2> = Outbox::new(RetryPolicy::MEASURED_CEILING);
    ob.track(&probe_frame(1), 0).unwrap();
    ob.track(&probe_frame(2), 0).unwrap();
    assert_eq!(ob.track(&probe_frame(3), 0), Err(DeliveryError::Full));
    assert_eq!(ob.len(), 2, "the existing entries survive");

    assert_eq!(ob.track(&[0u8; 4], 0), Err(DeliveryError::BadFrame));
}

/// Only frames addressed to us, asking for it, warrant an acknowledgement.
#[test]
fn only_a_want_ack_frame_addressed_to_us_is_acknowledged() {
    let f = probe_frame(0xAA00_0006);           // to = 0x11112222, want_ack = true
    assert!(wants_acknowledgement(&f, 0x1111_2222));
    assert!(!wants_acknowledgement(&f, 0x9999_9999), "not addressed to us");
    assert!(!wants_acknowledgement(&[0u8; 4], 0x1111_2222), "too short to have a header");
}

/// SEND_ONCE never retransmits, which is the safe default for a shared channel.
#[test]
fn send_once_never_retransmits() {
    let mut ob: Outbox<2> = Outbox::new(RetryPolicy::SEND_ONCE);
    let mut duty = wide_duty();
    ob.track(&probe_frame(0xAA00_0007), 0).unwrap();
    assert!(ob.next_due(u64::from(u32::MAX), 100_000, &mut duty).is_none());
    assert_eq!(ob.reap(u64::from(u32::MAX)), Some((0x7e57_0001, 0xAA00_0007)));
}

/// Build an acknowledgement frame for the bench, through the shipped code path.
///
/// This deliberately calls `delivery::acknowledgement` rather than assembling
/// the bytes here: the point of the exercise is to prove the function we ship
/// produces something a stock node accepts, and a reimplementation in the test
/// would prove only that two of our own things agree.
///
/// Channel-encrypted, because measurement showed the reply travels on the
/// channel even when acknowledging a PKI message. `want_ack` is left unset —
/// our deliberate deviation from upstream, which does set it.
#[test]
fn emit_ack_for_the_bench() {
    const FROM: u32 = 0x7e57_0001;
    let (Ok(to_s), Ok(req_s)) = (std::env::var("ACK_TO"), std::env::var("ACK_REQUEST_ID")) else {
        println!("ACK_FRAME skipped — set ACK_TO and ACK_REQUEST_ID");
        return;
    };
    let to = u32::from_str_radix(to_s.trim_start_matches("0x"), 16).expect("ACK_TO hex");
    let request_id =
        u32::from_str_radix(req_s.trim_start_matches("0x"), 16).expect("ACK_REQUEST_ID hex");
    let id: u32 = std::env::var("ACK_ID").ok()
        .and_then(|v| u32::from_str_radix(v.trim_start_matches("0x"), 16).ok())
        .unwrap_or(0x0bad_ac10);

    let ack = acknowledgement(request_id);
    assert_eq!(ack.payload, &[0x18, 0x00], "the measured bytes, not a generated zero");

    let mut payload = [0u8; 64];
    let plen = ack.encode(&mut payload).expect("ack encode");

    let Psk::Aes128(key) = expand_psk(&[0x01]).unwrap() else { panic!() };
    let header = Header {
        to,
        from: FROM,
        id,
        hop_limit: 3,
        hop_start: 3,
        want_ack: false,
        channel: channel_hash(b"LongFast", &key),
        relay_node: (FROM & 0xFF) as u8,
        ..Header::default()
    };
    let mut fb = [0u8; frame::MAX_FRAME];
    let n = frame::encode(&header, &payload[..plen], &key, 0, &mut fb).expect("frame encode");
    println!("ACK_FRAME {}", fb[..n].iter().map(|b| format!("{b:02x}")).collect::<String>());
}

/// A NodeInfo carrying `want_response`, which makes a stock node reply with its
/// own — one of the few ways to elicit a *stock-originated* frame on demand.
///
/// Meshtastic nodes are deliberately quiet: their spontaneous broadcasts are
/// minutes to hours apart, so waiting for variety does not work. Requests that
/// compel a reply do.
#[test]
fn emit_nodeinfo_request_for_the_bench() {
    const FROM: u32 = 0x7e57_0001;
    let Ok(to_s) = std::env::var("REQ_TO") else {
        println!("NODEINFO_REQUEST_FRAME skipped — set REQ_TO");
        return;
    };
    let to = u32::from_str_radix(to_s.trim_start_matches("0x"), 16).expect("REQ_TO hex");
    let id: u32 = std::env::var("REQ_ID").ok()
        .and_then(|v| u32::from_str_radix(v.trim_start_matches("0x"), 16).ok())
        .unwrap_or(0x0bad_1f00);

    let Psk::Aes128(key) = expand_psk(&[0x01]).unwrap() else { panic!() };
    let user = User {
        id: b"!7e570001",
        long_name: b"tethermesh",
        short_name: b"tm",
        macaddr: &[0, 0, 0, 0, 0, 0],
        hw_model: 43,
        ..User::default()
    };
    let mut ub = [0u8; 128];
    let ulen = user.encode(&mut ub).expect("User encode");
    let data = Data {
        portnum: PortNum::NODEINFO_APP.0,
        payload: &ub[..ulen],
        want_response: true,     // the part that compels a reply
        ..Data::default()
    };
    let mut payload = [0u8; 200];
    let plen = data.encode(&mut payload).expect("Data encode");

    let header = Header {
        to, from: FROM, id, hop_limit: 3, hop_start: 3,
        channel: channel_hash(b"LongFast", &key),
        relay_node: (FROM & 0xFF) as u8, ..Header::default()
    };
    let mut fb = [0u8; frame::MAX_FRAME];
    let n = frame::encode(&header, &payload[..plen], &key, 0, &mut fb).expect("frame encode");
    println!("NODEINFO_REQUEST_FRAME {}", fb[..n].iter().map(|b| format!("{b:02x}")).collect::<String>());
}
