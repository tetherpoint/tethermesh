/// Memory is bounded, and eviction is oldest-first.
#[test]
fn the_oldest_entry_is_evicted_when_full() {
    const N: usize = 4;
    let mut h: PacketHistory<N> = PacketHistory::new();
    for id in 0..N as u32 {
        assert_eq!(h.observe(1, id), Seen::New);
    }
    assert_eq!(h.len(), N);
    assert_eq!(h.capacity(), N);

    // One more evicts the oldest, and only the oldest.
    assert_eq!(h.observe(1, 99), Seen::New);
    assert_eq!(h.len(), N, "history grew past its capacity");
    assert!(!h.contains(1, 0), "the oldest entry survived eviction");
    for id in 1..N as u32 {
        assert!(h.contains(1, id), "id {id} was evicted out of order");
    }
    assert!(h.contains(1, 99));
}

/// Far more traffic than capacity must neither grow nor wrap incorrectly.
#[test]
fn sustained_traffic_stays_bounded_and_remembers_the_most_recent() {
    const N: usize = 16;
    let mut h: PacketHistory<N> = PacketHistory::new();
    for id in 0..10_000u32 {
        assert_eq!(h.observe(7, id), Seen::New, "id {id} wrongly seen as a duplicate");
        assert!(h.len() <= N);
    }
    // The most recent N are remembered; anything older is not.
    for back in 1..=N as u32 {
        assert!(h.contains(7, 10_000 - back), "recent id was forgotten");
    }
    assert!(!h.contains(7, 10_000 - N as u32 - 1), "an evicted id came back");
}

/// A duplicate must not refresh its own entry, or one chattering node's
/// retransmissions would hold its slot while evicting everyone else's.
#[test]
fn repeats_do_not_keep_an_entry_alive() {
    const N: usize = 4;
    let mut h: PacketHistory<N> = PacketHistory::new();
    h.observe(1, 0);
    for _ in 0..50 {
        assert_eq!(h.observe(1, 0), Seen::Duplicate);
    }
    // Fill past capacity with other traffic; the repeated entry must age out
    // like anything else.
    for id in 1..=N as u32 {
        h.observe(2, id);
    }
    assert!(!h.contains(1, 0), "a repeated entry outlived its age");
}

/// The header codec against REAL captured frames.
///
/// These bytes came off the air from a stock Meshtastic node, so this is the
/// one test in the suite that can catch an endianness or bit-position error.
/// A round-trip against our own encoder cannot: it would agree with itself
/// perfectly while being wrong on the wire.
#[test]
fn header_decodes_and_re_encodes_real_captured_frames() {
    let doc = fs::read_to_string(captures_dir().join("on_air_frames.json"))
        .expect("cannot read on_air_frames.json");
    let raws: Vec<&str> = {
        let mut v = Vec::new();
        let mut from = 0usize;
        while let Some(hit) = doc[from..].find("\"raw_hex\"") {
            let abs = from + hit;
            if let Some(s) = json_str(&doc[abs..], "raw_hex") {
                v.push(s);
            }
            from = abs + 9;
        }
        v
    };
    assert!(raws.len() >= 3, "expected at least 3 captured frames, found {}", raws.len());

    for (i, hex) in raws.iter().enumerate() {
        let frame = hex_to_bytes(hex);
        assert!(frame.len() > HEADER_LEN, "frame {i} is shorter than a header");

        let h = Header::decode(&frame).expect("failed to decode a real frame");

        // Cross-checks against facts established by other means entirely.
        //
        // Addressing is asserted per frame rather than blanket-broadcast. The
        // original corpus was all broadcasts and this read `is_broadcast()` for
        // every entry — a property of that sample, not of frames. It broke the
        // moment a Routing reply addressed to us was added, which is the
        // corpus doing its job.
        assert!(
            h.is_broadcast() || h.to == 0x7e57_0001,
            "frame {i}: addressed to 0x{:08x}, which is neither broadcast nor us",
            h.to
        );
        assert_eq!(h.from, 0x3369_e764, "frame {i}: sender does not match the transmitting board");
        assert_eq!(h.channel, 0x08, "frame {i}: channel hash should be LongFast's verified 0x08");
        assert_eq!(
            h.relay_node,
            (h.from & 0xFF) as u8,
            "frame {i}: relay_node must be the low byte of the sender"
        );
        // INVARIANTS, not sample values. This block asserted hop_limit == 3,
        // hop_start == 3 and !want_ack — all true of the original three
        // broadcasts and none of them true of a Routing reply, which travels
        // at hop_limit 2 with hop_start 2. Extending the corpus exposed four
        // such assumptions in one test; they were properties of the sample
        // wearing the clothes of properties of the protocol.
        assert!(h.hop_start > 0, "frame {i}: hop_start of zero is unusable");
        assert!(
            h.hop_limit <= h.hop_start,
            "frame {i}: hop_limit {} exceeds hop_start {} — a frame cannot have \
             more hops left than it began with",
            h.hop_limit, h.hop_start
        );
        assert!(!h.via_mqtt);

        // next_hop is a RULE, not a constant. This read `assert_eq!(h.next_hop, 0)`
        // while the corpus was broadcasts only. An addressed Routing reply
        // carries next_hop = the last byte of the destination node number,
        // which is the documented behaviour — "Last byte of the node number...
        // Set by the firmware internally" — observed directly for the first
        // time when the corpus grew.
        if h.is_broadcast() {
            assert_eq!(h.next_hop, 0, "frame {i}: a broadcast has no next hop");
        } else {
            assert_eq!(
                h.next_hop,
                (h.to & 0xFF) as u8,
                "frame {i}: an addressed frame carries the destination's last byte as next_hop"
            );
        }

        // And byte-exact back out again.
        assert_eq!(
            h.encode()[..],
            frame[..HEADER_LEN],
            "frame {i} did not re-encode to the captured bytes"
        );
    }
}

/// Endianness is the error this catches, so state it as its own assertion.
#[test]
