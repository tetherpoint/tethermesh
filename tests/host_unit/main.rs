/// Malformed input comes from the mesh, so every one of these must be an
/// error and none of them a panic. This is the negative twin of the
/// round-trip gate.
#[test]
fn malformed_input_errors_and_never_panics() {
    let cases: &[(&str, &[u8])] = &[
        ("truncated length-delimited", &[0x0a, 0x05, 0x01]),
        ("varint never terminates", &[0x08, 0x80, 0x80, 0x80]),
        ("varint longer than 64 bits", &[
            0x08, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x02,
        ]),
        ("group wire type 3", &[0x0b]),
        ("unassigned wire type 7", &[0x0f]),
        ("field number zero", &[0x00, 0x01]),
        ("truncated fixed32", &[0x0d, 0x01, 0x02]),
        ("truncated fixed64", &[0x09, 0x01, 0x02, 0x03]),
    ];
    for (name, bytes) in cases {
        let mut reader = Reader::new(bytes);
        // Drain: the error may surface on any field, not only the first.
        let errored = loop {
            match reader.next_field() {
                Ok(Some(_)) => continue,
                Ok(None) => break false,
                Err(_) => break true,
            }
        };
        assert!(
            errored,
            "{name}: accepted malformed input {bytes:02x?} instead of rejecting it"
        );
    }
}

